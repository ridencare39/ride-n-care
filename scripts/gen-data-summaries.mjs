#!/usr/bin/env bun
/**
 * Generates the slim summary modules used by global chrome (nav.ts, schema.ts,
 * homepage, index pages, area pages) from the full content modules.
 *
 * Why: services.ts / car-services.ts / answer-pages.ts / guides.ts are ~230 KB
 * of page content. Global chrome only needs slugs/labels — importing the full
 * modules pulls everything into the shared client bundle. The generated
 * summary modules are the single import point for chrome; the full modules
 * stay the single source of truth and are imported only by the routes that
 * render the content.
 *
 * Usage:
 *   bun scripts/gen-data-summaries.mjs          # check: fail if summaries are stale
 *   bun scripts/gen-data-summaries.mjs --write  # regenerate the summary modules
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { SERVICES } from "../src/lib/services";
import { CAR_SERVICES } from "../src/lib/car-services";
import { ANSWER_CATEGORIES, ANSWER_PAGES } from "../src/lib/answer-pages";
import { GUIDES } from "../src/lib/guides";

const j = (v) => JSON.stringify(v);
const obj = (pairs) => `{ ${pairs.map(([k, v]) => `${k}: ${v}`).join(", ")} }`;

const serviceSummaryLine = (s) =>
  `  ${obj([
    ["slug", j(s.slug)],
    ["name", j(s.name)],
    ["serviceType", j(s.serviceType)],
    ["local", String(Boolean(s.local))],
    ["title", j(s.title)],
    ["description", j(s.description)],
    ["summary", j(s.summary)],
    ["priceFrom", s.priceFrom != null ? String(s.priceFrom) : "undefined"],
    ["faqs", j(s.faqs)],
  ])},`;

const serviceSummary = `/**
 * Slim service index (slug / name / serviceType / local) for global chrome —
 * nav.ts, schema.ts, area pages and cross-link lists — so the full content
 * modules (services.ts, car-services.ts) stay out of the shared client bundle
 * and load only on the routes that render them.
 *
 * GENERATED by scripts/gen-data-summaries.mjs — do not edit by hand. Run
 * \`bun scripts/gen-data-summaries.mjs --write\` after changing the detail
 * files; scripts/test-data-sync.mjs fails when this drifts.
 */
export interface ServiceSummary {
  slug: string;
  /** Nav / card label */
  name: string;
  serviceType: string;
  /** Whether /<slug>/<area> local landing pages exist for this service. */
  local: boolean;
  /** <title> tag for the service page (route head runs in the shared bundle). */
  title: string;
  description: string;
  /** Answer-first summary paragraph (also the Service schema description). */
  summary: string;
  /** Lowest confirmed package price, when one exists. */
  priceFrom?: number;
  /** Visible-page FAQs — FAQPage JSON-LD must mirror them (route head). */
  faqs: [string, string][];
}

export const SERVICE_SUMMARY: ServiceSummary[] = [
${SERVICES.map(serviceSummaryLine).join("\n")}
];

export const CAR_SERVICE_SUMMARY: ServiceSummary[] = [
${CAR_SERVICES.map(serviceSummaryLine).join("\n")}
];

/** Services that get /<service>/<area> local landing pages. */
export const LOCAL_SERVICE_SUMMARY: ServiceSummary[] = SERVICE_SUMMARY.filter((s) => s.local);

export const getServiceSummary = (slug: string) => SERVICE_SUMMARY.find((s) => s.slug === slug);
export const getCarServiceSummary = (slug: string) => CAR_SERVICE_SUMMARY.find((s) => s.slug === slug);
`;

const answerSummary = `/**
 * Slim answer-page index (slug / question / category / meta / services) plus
 * the service- and area-scoped helpers. Global chrome, the homepage and
 * cross-link modules import THIS module; the full answer content
 * (answer-pages.ts) is imported only by /answers/$slug.
 *
 * GENERATED by scripts/gen-data-summaries.mjs — do not edit by hand. Run
 * \`bun scripts/gen-data-summaries.mjs --write\` after changing answer-pages.ts;
 * scripts/test-data-sync.mjs fails when this drifts.
 */
export type AnswerCategory =
${ANSWER_CATEGORIES.map((c) => `  | ${j(c.id)}`).join("\n")};

export const ANSWER_CATEGORIES: { id: AnswerCategory; label: string }[] = [
${ANSWER_CATEGORIES.map((c) => `  ${obj([["id", j(c.id)], ["label", j(c.label)]])},`).join("\n")}
];

export interface AnswerPageSummary {
  slug: string;
  /** The question, used verbatim as the page H1. */
  question: string;
  category: AnswerCategory;
  /** 120–155 char meta description; also used for related-answer scoring. */
  meta?: string;
  /** Service slugs this answer links to. */
  services: string[];
}

export const ANSWER_PAGE_SUMMARY: AnswerPageSummary[] = [
${ANSWER_PAGES.map((p) => `  ${obj([["slug", j(p.slug)], ["question", j(p.question)], ["category", j(p.category)], ["meta", p.meta ? j(p.meta) : "undefined"], ["services", j(p.services)]])},`).join("\n")}
];

export const getAnswerSummary = (slug: string) => ANSWER_PAGE_SUMMARY.find((p) => p.slug === slug);

/** Answer pages that link to a given service slug (for "Related answers" on service pages). */
export function answersForService(slug: string, limit = 4): AnswerPageSummary[] {
  return ANSWER_PAGE_SUMMARY.filter((p) => p.services.includes(slug)).slice(0, limit);
}

/**
 * Answers relevant to a locality: vehicle + booking questions apply everywhere;
 * coverage answers mention the area network. Drives the "Related answers"
 * module on /areas/* pages so every area page links into the answers cluster.
 */
export function answersForArea(areaName: string, limit = 4): AnswerPageSummary[] {
  const byCategory = ["coverage", "cost", "time", "trust", "care"]
    .map((cat) => ANSWER_PAGE_SUMMARY.filter((p) => p.category === cat))
    .flat();
  const seen = new Set<string>();
  const picked: AnswerPageSummary[] = [];
  for (const p of byCategory) {
    if (picked.length >= limit) break;
    if (seen.has(p.slug)) continue;
    seen.add(p.slug);
    picked.push(p);
  }
  // One locality-aware entry keeps the block from being purely generic.
  const coverage = ANSWER_PAGE_SUMMARY.find((p) => p.slug === "areas-covered");
  if (coverage && !seen.has(coverage.slug)) picked.unshift(coverage);
  return picked.slice(0, limit);
}
`;

const guideSummary = `/**
 * Slim guide index (slug / titles / summary / read time) for the homepage,
 * /guides and cross-link modules. The full guide bodies (guides.ts) load only
 * on /guides/$slug.
 *
 * GENERATED by scripts/gen-data-summaries.mjs — do not edit by hand. Run
 * \`bun scripts/gen-data-summaries.mjs --write\` after changing guides.ts;
 * scripts/test-data-sync.mjs fails when this drifts.
 */
export interface GuideSummary {
  slug: string;
  title: string;
  h1: string;
  description: string;
  /** Answer-first summary paragraph. */
  summary: string;
  published: string;
  readMinutes: number;
}

export const GUIDE_SUMMARY: GuideSummary[] = [
${GUIDES.map((g) => `  ${obj([["slug", j(g.slug)], ["title", j(g.title)], ["h1", j(g.h1)], ["description", j(g.description)], ["summary", j(g.summary)], ["published", j(g.published)], ["readMinutes", String(g.readMinutes)]])},`).join("\n")}
];

export const getGuideSummary = (slug: string) => GUIDE_SUMMARY.find((g) => g.slug === slug);
`;

const FILES = {
  "src/lib/service-summary.ts": serviceSummary,
  "src/lib/answer-page-summary.ts": answerSummary,
  "src/lib/guide-summary.ts": guideSummary,
};

const write = process.argv.includes("--write");
let stale = 0;
for (const [path, content] of Object.entries(FILES)) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (current === content) {
    console.log(`OK    ${path}`);
    continue;
  }
  if (write) {
    writeFileSync(path, content);
    console.log(`WROTE ${path} (${content.length} bytes)`);
  } else {
    console.log(`STALE ${path} — run with --write to regenerate`);
    stale++;
  }
}
if (!write && stale > 0) process.exit(1);
